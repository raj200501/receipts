def test_the_banked_failure_log_splits_the_missing_runs(tmp_path: Path) -> None:
    pairs = layout(tmp_path, per_cell=8)
    missing = pairs[:1]
    kept = pairs[1:]
    shutil.rmtree(tmp_path / analyze_e4.RUNS)
    bank(tmp_path / analyze_e4.RUNS, records_of(kept))
    write_rows(tmp_path, bank_rows(kept))
    run_id = str(records_of(missing)[0]["run_id"])
    log = tmp_path / analyze_e4.FAILURES
    log.write_text(
        "".join(
            json.dumps({"run_id": run_id, "attempt": n, "error": f"SYNTHETIC {n}"}) + "\n"
            for n in (1, 2, 3)
        ),
        encoding="utf-8",
    )
    assert run(tmp_path) == 0
    data = quick(tmp_path)
    accounting = data["runs"]["accounting"]
    assert accounting["failure_log"] == "banked" and accounting["excluded"]["count"] == 1
    assert accounting["excluded"]["runs"][0]["errors"] == [
        "SYNTHETIC 1",
        "SYNTHETIC 2",
        "SYNTHETIC 3",
    ]
    assert data["provenance"]["inputs"][analyze_e4.FAILURES] == sha256(log)
    assert any(d["kind"] == "shortfall" for d in data["deviations"])
    log.write_text('{"attempt": 1}\n', encoding="utf-8")
    assert run(tmp_path) == 1


