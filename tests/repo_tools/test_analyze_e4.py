def test_without_a_plan_or_e1_the_gaps_are_recorded(tmp_path: Path) -> None:
    layout(tmp_path)
    (tmp_path / "artifacts" / "studies" / "e4" / "plan.json").unlink()
    (tmp_path / "artifacts" / "e1" / "runs.jsonl").unlink()
    out = tmp_path / "elsewhere.json"
    assert run(tmp_path, "--out", str(out)) == 0
    data = json.loads(out.read_text(encoding="utf-8"))
    assert any("No E4 plan was checked" in d for d in data["deviations"])
    assert data["held_out"]["e1_tasks_checked"] is False


def test_e1_task_ids_reads_runs_and_plan(tmp_path: Path) -> None:
    assert analyze_e4.e1_task_ids(tmp_path) == (None, [])
    plan = tmp_path / "artifacts" / "studies" / "e1" / "plan.json"
    plan.parent.mkdir(parents=True)
    plan.write_text(
        json.dumps({"notes": json.dumps({"e1_tasks": ["py-a"]}), "runs": [{"task_id": "py-b"}]}),
        encoding="utf-8",
    )
    tasks, sources = analyze_e4.e1_task_ids(tmp_path)
    assert tasks == ["py-a", "py-b"] and sources == ["artifacts/studies/e1/plan.json"]
    rows = tmp_path / "artifacts" / "e1" / "runs.jsonl"
    rows.parent.mkdir(parents=True)
    rows.write_text(json.dumps({"task_id": "py-c"}) + "\n\n", encoding="utf-8")
    tasks, sources = analyze_e4.e1_task_ids(tmp_path)
    assert tasks == ["py-a", "py-b", "py-c"] and len(sources) == 2


