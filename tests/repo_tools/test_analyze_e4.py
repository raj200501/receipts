def sha256(path: Path) -> str:
    """SHA-256 of a file's bytes."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_json(path: Path, data: Any) -> None:
    """Write JSON, creating parent directories."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data), encoding="utf-8")


def write_rows(root: Path, rows: Sequence[dict[str, Any]]) -> None:
    """The rows and their banking provenance, as ``bank_study e4`` writes them (SYNTHETIC)."""
    aggregate.write_jsonl(root / analyze_e4.ROWS, rows)
    digest = sha256(root / analyze_e4.ROWS)
    write_json(root / analyze_e4.ROWS_PROVENANCE, {"study": "e4", "rows_sha256": digest})


def write_prereg(root: Path, *, per_cell: int | None = 8, digest: str | None = None) -> None:
    """A SYNTHETIC E4 preregistration with the machine-readable lines asked for."""
    text = "# SYNTHETIC E4 preregistration for a test\n"
    if per_cell is not None:
        text += f"planned_runs_per_cell: {per_cell}\n"
    if digest is not None:
        text += f"plan_sha256: {digest}\n"
    (root / "prereg").mkdir(exist_ok=True)
    (root / PREREG).write_text(text, encoding="utf-8")


def layout(
    root: Path,
    *,
    per_cell: int = 8,
    e1_tasks: tuple[str, ...] = ("py-e1-only",),
    pairs: Sequence[Pair] | None = None,
) -> list[Pair]:
    """A SYNTHETIC repository layout with everything analyze_e4.py reads."""
    pairs = list(pairs) if pairs is not None else synthetic_study(per_cell=per_cell)
    records = records_of(pairs)
    bank(root / analyze_e4.RUNS, records)
    write_rows(root, bank_rows(pairs))
    write_json(root / analyze_e4.PLAN, plan_for(records))
    write_json(root / analyze_e4.SEEDED_EVAL, seeded_eval())
    e1 = root / analyze_e4.E1_ROWS
    e1.parent.mkdir(parents=True, exist_ok=True)
    e1.write_text(
        "".join(
            json.dumps({"run_id": f"e1-{t}", "task_id": t, "synthetic": True}) + "\n"
            for t in e1_tasks
        ),
        encoding="utf-8",
    )
    write_prereg(root, per_cell=len(records) // 8, digest=sha256(root / analyze_e4.PLAN))
    return pairs


def run(root: Path, *extra: str) -> int:
    """A quick check (20 resamples) written to ``<root>/quick-check.json``, not the default."""
    return analyze_e4.main(
        ["--root", str(root), "--n-boot", "20", "--out", str(root / QUICK), *extra]
    )


def quick(root: Path) -> dict[str, Any]:
    """The artifact :func:`run` wrote."""
    data: dict[str, Any] = json.loads((root / QUICK).read_text(encoding="utf-8"))
    return data


