def confirmatory_repo(root: Path, commit: Commit) -> tuple[list[Pair], str]:
    """A scratch repository where every confirmatory condition holds (SYNTHETIC inputs).

    The analysis code is copied in and committed with SYNTHETIC instrument files, tasks,
    the plans, and a preregistration whose lines record the plan; the seeded evaluation
    records the instrument trees of that commit; the freeze commit adds the LOCK entry;
    the runs record the freeze commit, the committed task trees, the pinned models, and
    bubblewrap, and their rows carry the checkout's instrument record. The records are
    copies of SYNTHETIC ones with the synthetic flag stripped, used only here.
    """
    copy_analysis_code(root)
    for rel in SCORING_PATHS:
        (root / rel).mkdir(parents=True, exist_ok=True)
        (root / rel / "SYNTHETIC.txt").write_text(f"SYNTHETIC {rel}\n", encoding="utf-8")
    pairs = unlabeled(synthetic_study(per_cell=8))
    records = records_of(pairs)
    tasks = sorted({str(r["task_id"]) for r in records})
    for task in tasks:
        (root / "bench" / "tasks" / task).mkdir(parents=True)
        (root / "bench" / "tasks" / task / "task.toml").write_text(f"id = '{task}'\n")
    write_json(root / analyze_e4.PLAN, plan_for(records))
    notes = {"e1_tasks": ["py-e1-only"], "e4_tasks": tasks}
    e1_plan = {"study": "e1", "notes": json.dumps(notes), "runs": [], "arms": plan_arms()}
    write_json(root / analyze_e4.E1_PLAN, e1_plan)
    write_prereg(root, per_cell=8, digest=sha256(root / analyze_e4.PLAN))
    first = commit(root, "SYNTHETIC code, tasks, plans, prereg")
    trees = {rel: _git(root, "rev-parse", f"{first}:{rel}").strip() for rel in SCORING_PATHS}
    evaluation = seeded_eval()
    evaluation["instrument"] = {"commit": first, "paths": list(SCORING_PATHS), "trees": trees}
    write_json(root / analyze_e4.SEEDED_EVAL, evaluation)
    prereg.freeze(root, PREREG, "2026-11-04")
    freeze = commit(root, "SYNTHETIC freeze")
    rebank(root, pairs, freeze)
    return pairs, freeze


def rebank(
    root: Path,
    pairs: Sequence[Pair],
    sha: str,
    *,
    tree: Callable[[str], str] | None = None,
    instrument: dict[str, Any] | None = None,
) -> None:
    """Bank SYNTHETIC unlabeled pairs as launched from ``sha``, with their rows."""
    runs = root / analyze_e4.RUNS
    if runs.exists():
        shutil.rmtree(runs)
    banked: list[Pair] = []
    for record, scored in pairs:
        copied = json.loads(json.dumps(record))
        task = str(copied["task_id"])
        copied["provenance"].update(
            git_sha=sha,
            snapshot_of=sha,
            task_tree_sha256=(tree or (lambda t: tree_sha256(root / "bench" / "tasks" / t)))(task),
        )
        banked.append((copied, scored))
    bank(runs, records_of(banked))
    record = instrument if instrument is not None else rescore.instrument_record(root)
    write_rows(root, aggregate.e4_rows(banked, record))


def test_end_to_end_confirmatory_artifact_and_each_refusal(
    git_repo: Path,
    commit: Commit,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    """Every condition of prereg 0002 section 7 holds, then each is broken in turn."""
    monkeypatch.setattr(results_e4, "analyze", quick_analyze)
    pairs, freeze = confirmatory_repo(git_repo, commit)
    args = ["--root", str(git_repo), "--confirmatory"]
    assert analyze_e4.main(args) == 0, capsys.readouterr().err
    data = json.loads((git_repo / DEFAULT_OUT).read_text(encoding="utf-8"))
    assert data["confirmatory"] is True and data["confirmatory_blockers"] == []
    assert data["prereg_status"]["freeze_commit"] == freeze
    assert data["run_checks"]["freeze_commit"] == freeze
    assert data["provenance"]["freeze_commit"] == freeze
    capsys.readouterr()
    (git_repo / DEFAULT_OUT).unlink()

    def refused(fragment: str) -> None:
        assert analyze_e4.main(args) == 1
        err = capsys.readouterr().err
        assert "refusing a confirmatory E4 artifact" in err and fragment in err, err

    # A run launched from a commit before the freeze.
    before = _git(git_repo, "rev-parse", f"{freeze}~1").strip()
    rebank(git_repo, pairs, before)
    refused("the run's code is not from the freeze commit or a later one")
    # A run on task files other than the committed ones.
    rebank(git_repo, pairs, freeze, tree=lambda t: "0" * 64)
    refused("the run's task files differ from the ones committed in the freeze commit")
    # Rows banked with another instrument, or from uncommitted code.
    other = {**rescore.instrument_record(git_repo), "trees": {SCORING_PATHS[0]: "1" * 40}}
    rebank(git_repo, pairs, freeze, instrument=other)
    refused("the row's instrument trees differ from the evaluated instrument's")
    dirty = {**rescore.instrument_record(git_repo), "dirty": True, "uncommitted": ["x"]}
    rebank(git_repo, pairs, freeze, instrument=dirty)
    refused("the row was banked from uncommitted code (instrument_dirty)")
    rebank(git_repo, pairs, freeze)
    # Uncommitted analysis code.
    tool = git_repo / "tools" / "analyze_e4.py"
    kept = tool.read_text(encoding="utf-8")
    tool.write_text(kept + "# SYNTHETIC edit\n", encoding="utf-8")
    refused("the analysis code has uncommitted changes")
    tool.write_text(kept, encoding="utf-8")
    # A plan that is not the recorded one.
    plan = git_repo / analyze_e4.PLAN
    plan_text = plan.read_text(encoding="utf-8")
    plan.write_text(plan_text + "\n", encoding="utf-8")
    refused("differs from the plan_sha256 the prereg records")
    plan.write_text(plan_text, encoding="utf-8")
    # E4 arms that are not E1's.
    e1_plan = json.loads((git_repo / analyze_e4.E1_PLAN).read_text(encoding="utf-8"))
    e1_plan["arms"][0]["agent"]["max_turns"] = 25
    write_json(git_repo / analyze_e4.E1_PLAN, e1_plan)
    refused("arm ma-qwen7b differs from the E1 plan's arm ma-qwen7b")
    e1_plan["arms"][0]["agent"]["max_turns"] = 16
    write_json(git_repo / analyze_e4.E1_PLAN, e1_plan)
    # Everything restored: confirmatory again.
    assert analyze_e4.main(args) == 0, capsys.readouterr().err


