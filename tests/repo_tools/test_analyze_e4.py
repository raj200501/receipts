def test_the_plan_hash_recorded_in_the_prereg_is_checked(tmp_path: Path) -> None:
    layout(tmp_path)
    plan = tmp_path / "artifacts" / "studies" / "e4" / "plan.json"
    digest = hashlib.sha256(plan.read_bytes()).hexdigest()
    (tmp_path / PREREG).write_text(f"# SYNTHETIC prereg\nplan_sha256: {digest}\n", "utf-8")
    assert run(tmp_path) == 0
    data = quick(tmp_path)
    assert data["runs"]["plan"]["matches_prereg"] is True
    assert data["runs"]["plan"]["sha256"] == digest


def test_e4_tasks_must_come_from_the_split_in_the_e1_plan(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    records = layout(tmp_path)
    assert analyze_e4.split_e4_tasks(tmp_path) is None
    plan = tmp_path / "artifacts" / "studies" / "e1" / "plan.json"
    plan.parent.mkdir(parents=True)
    tasks = sorted({r["task_id"] for r in records})
    notes = {"e1_tasks": ["py-e1-only"], "e4_tasks": tasks[1:]}
    plan.write_text(json.dumps({"notes": json.dumps(notes), "runs": []}), encoding="utf-8")
    assert analyze_e4.split_e4_tasks(tmp_path) == tasks[1:]
    assert run(tmp_path) == 1
    assert (
        f"outside the held-out split recorded in the E1 plan: {tasks[0]}" in capsys.readouterr().err
    )
    notes["e4_tasks"] = tasks
    plan.write_text(json.dumps({"notes": json.dumps(notes), "runs": []}), encoding="utf-8")
    assert run(tmp_path) == 0
    data = quick(tmp_path)
    assert data["held_out"]["split_checked"] is True and data["held_out"]["split_tasks"] == tasks
    plan.write_text(json.dumps({"notes": "not json", "runs": []}), encoding="utf-8")
    assert analyze_e4.split_e4_tasks(tmp_path) is None


def test_confirmatory_needs_e1_tasks_and_the_split_in_the_e1_plan(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """Review fix: --confirmatory is refused until both held-out checks can run.

    The runs stay labeled SYNTHETIC, so every request is refused; the refusal must name
    each held-out gap until E1's rows and the split recorded in the E1 plan are read.
    """
    records = layout(tmp_path)
    prereg.freeze(tmp_path, PREREG, "2026-11-04")
    args = ["--root", str(tmp_path), "--confirmatory"]
    assert analyze_e4.main(args) == 1
    err = capsys.readouterr().err
    assert "synthetic" in err and "no E1 plan records the held-out E4 split" in err
    assert "E1's task ids are unknown" not in err  # artifacts/e1/runs.jsonl was read
    (tmp_path / "artifacts" / "e1" / "runs.jsonl").unlink()
    assert analyze_e4.main(args) == 1
    assert "E1's task ids are unknown" in capsys.readouterr().err
    plan = tmp_path / "artifacts" / "studies" / "e1" / "plan.json"
    plan.parent.mkdir(parents=True)
    notes = {"e1_tasks": ["py-e1-only"], "e4_tasks": sorted({r["task_id"] for r in records})}
    plan.write_text(json.dumps({"notes": json.dumps(notes), "runs": []}), encoding="utf-8")
    assert analyze_e4.main(args) == 1
    err = capsys.readouterr().err
    assert "synthetic" in err and "held-out tasks" not in err
    assert not (tmp_path / DEFAULT_OUT).exists()


def test_quick_checks_never_write_the_default_artifact(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """Review fix (as in run_judges): non-preregistered settings need --out elsewhere."""
    layout(tmp_path)
    default = tmp_path / DEFAULT_OUT
    for extra in (["--n-boot", "20"], ["--seed", "7"], ["--n-agq", "4"]):
        assert analyze_e4.main(["--root", str(tmp_path), *extra]) == 1
        err = capsys.readouterr().err
        assert "a quick check" in err and "--out" in err and not default.exists()
    same = ["--root", str(tmp_path), "--n-boot", "20", "--out", str(default)]
    assert analyze_e4.main(same) == 1 and not default.exists()
    capsys.readouterr()
    assert run(tmp_path) == 0 and quick(tmp_path)["settings"]["n_boot"] == 20
    assert not default.exists()
    preregistered = results_e4.AnalysisSettings()
    assert analyze_e4.output_problem(tmp_path, default, settings=preregistered) is None


def test_an_exploratory_run_never_replaces_a_confirmatory_artifact(
    tmp_path: Path, capsys: pytest.CaptureFixture[str], monkeypatch: pytest.MonkeyPatch
) -> None:
    """Review fix (as in run_judges): the default path keeps a confirmatory artifact."""
    layout(tmp_path)
    default = tmp_path / DEFAULT_OUT
    default.parent.mkdir(parents=True)
    # A SYNTHETIC placeholder standing for a banked confirmatory artifact.
    placeholder = '{"confirmatory": true, "SYNTHETIC": "placeholder"}\n'
    default.write_text(placeholder, encoding="utf-8")

    def never(*_: Any, **__: Any) -> Any:
        raise AssertionError("a refused run must not analyze anything")

    monkeypatch.setattr(analyze_e4, "build", never)
    assert analyze_e4.main(["--root", str(tmp_path)]) == 1
    err = capsys.readouterr().err
    assert "holds a confirmatory artifact" in err and "--confirmatory" in err
    assert default.read_text(encoding="utf-8") == placeholder
    for other in ('{"confirmatory": false}\n', "not json\n", "[1]\n"):
        default.write_text(other, encoding="utf-8")
        assert analyze_e4.output_problem(tmp_path, default, confirmatory=False) is None
    assert analyze_e4.output_problem(tmp_path, tmp_path / QUICK, confirmatory=False) is None
    default.write_text(placeholder, encoding="utf-8")
    assert analyze_e4.output_problem(tmp_path, default, confirmatory=True) is None
