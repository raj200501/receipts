def test_task_tree_at_hashes_the_committed_task_as_run_study_does(
    git_repo: Path, commit: Commit
) -> None:
    task = git_repo / "bench" / "tasks" / "py-a"
    (task / "repo" / "sub").mkdir(parents=True)
    (task / "task.toml").write_text("id = 'py-a'\n", encoding="utf-8")
    (task / "repo" / "sub" / "x.py").write_bytes(b"print('SYNTHETIC')\n\x00\xff")
    (task / "repo-b.txt").write_text("SYNTHETIC sibling\n", encoding="utf-8")
    other = git_repo / "bench" / "tasks" / "py-ab"
    other.mkdir()
    (other / "task.toml").write_text("id = 'py-ab'\n", encoding="utf-8")
    first = commit(git_repo, "SYNTHETIC tasks")
    before = tree_sha256(task)
    assert analyze_e4.task_tree_at(git_repo, first, "py-a") == before
    (task / "task.toml").write_text("id = 'py-a'  # changed\n", encoding="utf-8")
    second = commit(git_repo, "SYNTHETIC task change")
    assert analyze_e4.task_tree_at(git_repo, first, "py-a") == before
    assert analyze_e4.task_tree_at(git_repo, second, "py-a") == tree_sha256(task) != before
